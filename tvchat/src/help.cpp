// help.cpp - the in-app help (F1).
#include "tvchat.h"

static const char *kHelpText =
    "tvchat  -  a Turbo Vision chat client                (Esc / Alt-F3 closes)\n"
    "\n"
    "THE THREE PANES\n"
    "  Servers (left)  .  Conversations (top right)  .  the chat (bottom right).\n"
    "  Tab / Shift-Tab move between them: servers -> conversations -> input.\n"
    "  Moving the highlight in Servers shows that server's conversations (and\n"
    "  the one you last had open there); moving it in Conversations shows that\n"
    "  conversation below.  Enter on a server connects it if need be and goes\n"
    "  to its conversations; Enter on a conversation goes to the input line.\n"
    "  Each server's list starts with its server messages (MOTD, notices,\n"
    "  errors, SASL results).\n"
    "\n"
    "ACCOUNTS   (~/.config/tvchat/tvchat.conf - see man tvchat-backend)\n"
    "  IRC, talk(1) and Delta Chat.  Accounts connect by\n"
    "  themselves ([chat] autoconnect) or by Chat > Connect / Disconnect (it acts on\n"
    "  the account picked in the Servers pane); the Chat menu\n"
    "  lists each one and its state - pick one to show it.  Passwords never go\n"
    "  in tvchat.conf: $TVCHAT_PASS_<ACCOUNT>, ~/.mu-tickets or ~/.netrc, for\n"
    "  the SASL login.  A channel you operate shows @ in front of its name (%\n"
    "  half-op, + voice).\n"
    "THE CHAT MENU   (the same for IRC, Delta Chat and talk; it reads what you give it)\n"
    "  Connect / Disconnect   the account picked in the Servers pane.\n"
    "  Chat with...           one box: a #channel, a nick, an email address or an\n"
    "                         invite link.  (New group... is a button there.)\n"
    "  Invite...              in a Delta Chat group it adds a person; otherwise it\n"
    "                         asks someone to the account (a channel, too): with a\n"
    "                         chat shown it sends the link there, to a person on any\n"
    "                         IRC or Delta Chat account; with a channel shown it asks\n"
    "                         which user in it to send the link to.  Copy link puts\n"
    "                         the link on the clipboard.\n"
    "  This chat...           the conversation shown: add or remove a member, rename\n"
    "                         a group, leave.\n"
    "  Send selection to >    Mail, Calendar or To-do: the lines selected in the log.\n"
    "  Pending...             only when something waits: an invitation, or a message\n"
    "                         tvmail asked to share.  (They also ask by themselves\n"
    "                         when they arrive.)\n"
    "  Devices >              second-device items, for a Delta Chat account with a\n"
    "                         core of its own (not one on the gateway).\n"
    "  The same words typed:  /chat, /invite, /leave, /name (/rename), /remove,\n"
    "                         /pending, /accept, /decline - /help lists them.\n"
    "\n"
    "DELTA CHAT   (protocol = deltachat: encrypted chat over a mailbox of its own)\n"
    "  Needs the official core, deltachat-rpc-server (see INSTALL.md).  Before\n"
    "  two people can write to each other they swap keys: Chat with... an email\n"
    "  address you hold no key for mails them an invitation; their tvchat asks\n"
    "  to accept, and the chat opens on both sides.  (Or give them the link from\n"
    "  Chat > Invite...; they paste it into Chat with...)  A\n"
    "  message from someone new waits as a request, and your reply accepts it.\n"
    "  Unlike IRC, Delta Chat's history is kept by the core, and PgUp reads it.\n"
    "  An invitation that comes by mail is found by the gateway (or, for an account\n"
    "  with a core of its own, by tvchat) and asks you by itself; Chat > Pending...\n"
    "  asks again.  Chat > This chat... has the group things (members, rename) and\n"
    "  Leave, which deletes a chat from this device (it asks first).  With tvmail\n"
    "  installed, Chat > Invite... can also mail the link to someone's ordinary address.\n"
    "  Delta Chat on several machines: the account lives on ONE (cpbee), behind the\n"
    "  gateway dcgw; every tvchat is a thin client with a token (gateway = HOST,\n"
    "  token = ... on the account: no key, database or mail login there) and all of\n"
    "  them see the same chats.  Floyd's !setup adds the account, !setup delta TOKEN\n"
    "  saves the token.  (DELTA-GATEWAY.md.)  A machine that wants its own copy can\n"
    "  use Chat > Devices > Add second device... on the one that has the account and\n"
    "  Devices > Use account from another device... on the other.\n"
    "\n"
    "TALKING\n"
    "  In the chat pane just type: Enter sends.  Up / Down recall what you sent\n"
    "  before (kept between sessions, never a NickServ / OPER / PASS line or one\n"
    "  that starts with a space); PgUp / PgDn / Shift-Up / Shift-Down scroll the\n"
    "  log, and PgUp at the top fetches older messages (from the server, too,\n"
    "  when it keeps history).  What you typed and did not send stays with its\n"
    "  conversation when you pick another; Alt-X asks before it is thrown away.\n"
    "  A line can be a command, the same words for IRC, talk and Delta Chat (the\n"
    "  server messages take only commands); //text sends a line that starts with /.\n"
    "  Type /help for the ones this account has, /help NAME to explain one:\n"
    "    /help  /status  /me  /shrug  /join  /query  /msg  /leave  /invite  /names\n"
    "    /whois  /nick  /name  /topic  /away  /ping  /clear  /quit  /quote\n"
    "  A lost connection is tried again by itself (after 2 s, 4 s, ... up to\n"
    "  5 minutes); Chat > Disconnect... stops that.\n"
    "  Unread messages count in both lists, in the window title while another\n"
    "  window is in front, and as \"N new\" on the status line.  A conversation\n"
    "  is read once the chat pane has the focus.\n"
    "  The log lives in memory only: it is gone when tvchat exits.\n"
    "\n"
    "TALK   (protocol = talk: talk(1) through the LAN master's talkd)\n"
    "  Chat > Join... a user (or user@host) calls them.  A call for you says\n"
    "  so on the status line and in the list (\"- calling you\"): show it and\n"
    "  press Enter (or Chat > Answer).  Chat > Leave hangs up or declines.\n"
    "  Two views, View > Talk view (Ctrl-T) switches the one shown:\n"
    "    classic  talk's own screen - you on top, them below; every key goes\n"
    "             as you type it (Backspace, Ctrl-U kill, Ctrl-W word too)\n"
    "    IRC      the log; a line goes when you press Enter, and \"... is\n"
    "             typing\" shows while their line is unfinished\n"
    "  An account starts in its talk_view (classic unless it says irc).\n"
    "\n"
    "FIND AND COPY   (the chat log, Help)\n"
    "  Edit > Find... / Find again search the text.\n"
    "  Shift-arrows / Shift-PgUp / PgDn or a mouse drag select whole lines;\n"
    "  Ctrl-Ins (Edit > Copy) copies them - everything, when nothing is\n"
    "  selected.  Long lines wrap; View > Wrap long lines turns that off.\n"
    "  Chat > Send selection to > Mail... emails the selected lines through tvmail.\n"
    "  A mail tvmail offered to share (sender and subject) asks you by itself and\n"
    "  is said in the [chat] share_to channel only after you agree.\n"
    "\n"
    "NOTIFICATIONS\n"
    "  Messages that need no answer are toasts at the bottom right: no key to press,\n"
    "  gone in a few seconds.  Window > Notification history keeps them.\n"
    "\n"
    "CONFIGURATION\n"
    "  File > Edit configuration... opens tvchat.conf in a window: F9 verifies the\n"
    "  text (nothing is connected), F8 verifies, saves and applies it to the running\n"
    "  backend (accounts you did not touch keep their connections), Ctrl-S only saves.\n"
    "\n"
    "KEYS AT A GLANCE\n"
    "  F1 help    F6 next window    Alt-0 window list    F10 menu\n"
    "  F7 Floyd, the assistant (File menu): the same Floyd as in tvmail and tvcal; !setup\n"
    "     checks this machine against the master Floyd and fixes what it can; help lists more\n"
    "  Tab pane   Enter send   PgUp older   Alt-X quit   Ctrl-L redraw\n"
    "\n"
    "MESSAGES FROM OTHER USERS\n"
    "  While tvchat runs, talk requests and write / wall messages from ordinary\n"
    "  users are kept off the screen ([ui] mesg in tvchat.conf).  Root's still\n"
    "  get through: Ctrl-L (Window > Redraw screen) clears them.\n";

TWindow *newHelpWindow(const TRect &bounds)
{
    return newTextWindow(bounds, "Help", kHelpText);
}
