// help.cpp - the in-app help (F1).
#include "tvchat.h"

static const char *kHelpText =
    "tvchat  -  a Turbo Vision chat client                (Esc / Alt-F3 closes)\n"
    "\n"
    "THE THREE PANES\n"
    "  Servers (left)  .  Conversations (top right)  .  the chat (bottom right).\n"
    "  Tab / Shift-Tab move between them: servers -> conversations -> input.\n"
    "  Moving the highlight in Servers shows that server's conversations (and\n"
    "  the one you last had open there); moving it in Conversations shows that\n"
    "  conversation below.  Enter on a server connects it if need be and goes\n"
    "  to its conversations; Enter on a conversation goes to the input line.\n"
    "  Each server's list starts with its server messages (MOTD, notices,\n"
    "  errors, SASL results).\n"
    "\n"
    "ACCOUNTS   (~/.config/tvchat/tvchat.conf - see man tvchat-backend)\n"
    "  IRC and talk(1) today, Delta Chat to come.  Accounts connect by\n"
    "  themselves ([chat] autoconnect) or by Chat > Connect...; the Chat menu\n"
    "  lists each one and its state - pick one to show it.  Passwords never go\n"
    "  in tvchat.conf: $TVCHAT_PASS_<ACCOUNT>, ~/.mu-tickets or ~/.netrc, for\n"
    "  the SASL login.\n"
    "  Chat > Join... a channel, or a nick to talk to; Chat > Leave parts the\n"
    "  conversation shown.\n"
    "\n"
    "TALKING\n"
    "  In the chat pane just type: Enter sends.  PgUp / PgDn / Up / Down scroll\n"
    "  the log; PgUp at the top fetches older messages (from the server, too,\n"
    "  when it keeps history).  What you typed and did not send stays with its\n"
    "  conversation when you pick another; Alt-X asks before it is thrown away.\n"
    "  A line can be a command - the server messages take only these:\n"
    "    /me ACTION         /join #CHANNEL [KEY]     /part [#CHANNEL] [REASON]\n"
    "    /msg NICK TEXT     /nick NEWNICK            /topic [NEW TOPIC]\n"
    "    /quote RAW IRC LINE        //text sends a line that starts with /\n"
    "  A lost connection is tried again by itself (after 2 s, 4 s, ... up to\n"
    "  5 minutes); Chat > Disconnect... stops that.\n"
    "  Unread messages count in both lists, in the window title while another\n"
    "  window is in front, and as \"N new\" on the status line.  A conversation\n"
    "  is read once the chat pane has the focus.\n"
    "  The log lives in memory only: it is gone when tvchat exits.\n"
    "\n"
    "TALK   (protocol = talk: talk(1) through the LAN master's talkd)\n"
    "  Chat > Join... a user (or user@host) calls them.  A call for you says\n"
    "  so on the status line and in the list (\"- calling you\"): show it and\n"
    "  press Enter (or Chat > Answer).  Chat > Leave hangs up or declines.\n"
    "  Two views, View > Talk view (Ctrl-T) switches the one shown:\n"
    "    classic  talk's own screen - you on top, them below; every key goes\n"
    "             as you type it (Backspace, Ctrl-U kill, Ctrl-W word too)\n"
    "    IRC      the log; a line goes when you press Enter, and \"... is\n"
    "             typing\" shows while their line is unfinished\n"
    "  An account starts in its talk_view (classic unless it says irc).\n"
    "\n"
    "FIND AND COPY   (the chat log, Help)\n"
    "  Edit > Find... / Find again search the text.\n"
    "  Shift-arrows / Shift-PgUp / PgDn or a mouse drag select whole lines;\n"
    "  Ctrl-Ins (Edit > Copy) copies them - everything, when nothing is\n"
    "  selected.  Long lines wrap; View > Wrap long lines turns that off.\n"
    "\n"
    "KEYS AT A GLANCE\n"
    "  F1 help    F6 next window    Alt-0 window list    F10 menu\n"
    "  Tab pane   Enter send   PgUp older   Alt-X quit   Ctrl-L redraw\n"
    "\n"
    "MESSAGES FROM OTHER USERS\n"
    "  While tvchat runs, talk requests and write / wall messages from ordinary\n"
    "  users are kept off the screen ([ui] mesg in tvchat.conf).  Root's still\n"
    "  get through: Ctrl-L (Window > Redraw screen) clears them.\n";

TWindow *newHelpWindow(const TRect &bounds)
{
    return newTextWindow(bounds, "Help", kHelpText);
}
